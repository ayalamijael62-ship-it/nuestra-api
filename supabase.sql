-- Tabla de favoritos y políticas de seguridad
-- =============================================

-- 1. Crear tabla de favoritos
CREATE TABLE IF NOT EXISTS public.favoritos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    imdb_id TEXT NOT NULL,
    titulo TEXT,
    anio TEXT,
    poster TEXT,
    tipo TEXT,

    -- Evita que un usuario guarde dos veces la misma película
    CONSTRAINT favoritos_user_imdb_unique UNIQUE (user_id, imdb_id)
);

-- 2. Habilitar Row Level Security
ALTER TABLE public.favoritos ENABLE ROW LEVEL SECURITY;

-- 3. Permisos para usuarios autenticados
REVOKE ALL ON TABLE public.favoritos FROM anon;
GRANT SELECT, INSERT, DELETE ON TABLE public.favoritos TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.favoritos_id_seq TO authenticated;

-- 4. Políticas de seguridad
-- Cada usuario solamente puede consultar sus propios favoritos.

DROP POLICY IF EXISTS "Ver favoritos propios" ON public.favoritos;

CREATE POLICY "Ver favoritos propios"
ON public.favoritos
FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

-- Cada usuario solamente puede agregar favoritos a su propia cuenta.

DROP POLICY IF EXISTS "Agregar favoritos propios" ON public.favoritos;

CREATE POLICY "Agregar favoritos propios"
ON public.favoritos
FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

-- Cada usuario solamente puede eliminar sus propios favoritos.

DROP POLICY IF EXISTS "Eliminar favoritos propios" ON public.favoritos;

CREATE POLICY "Eliminar favoritos propios"
ON public.favoritos
FOR DELETE
TO authenticated
USING (auth.uid() = user_id);

-- 5. Habilitar Realtime para sincronizar favoritos
ALTER TABLE public.favoritos REPLICA IDENTITY FULL;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_publication
        WHERE pubname = 'supabase_realtime'
    )
    AND NOT EXISTS (
        SELECT 1
        FROM pg_publication_tables
        WHERE pubname = 'supabase_realtime'
          AND schemaname = 'public'
          AND tablename = 'favoritos'
    ) THEN
        ALTER PUBLICATION supabase_realtime
        ADD TABLE public.favoritos;
    END IF;
END
$$;
